"""
Write build/values.tex: the numbers the figures quote, as macros, read from data/.

Final validation results per seed and for the bigram baseline, and each seed's critical head
(the one whose mean-ablation raises test loss most) with that rise. Formatting only.
"""

import csv

SEEDS = {'A': 'default-seed0', 'B': 'default-seed1', 'C': 'default-seed2'}
lines = ['% Generated by src/values.py from data/; do not edit.']


def rows(path: str) -> list[dict[str, str]]:
  with open(path) as f:
    return list(csv.DictReader(f))


for tag, run in [*SEEDS.items(), ('Bigram', 'bigram-seed0')]:
  last = rows(f'data/curves-{run}.csv')[-1]
  lines.append(f'\\def\\exact{tag}{{{100 * float(last["val_exact_match"]):.1f}}}\\def\\loss{tag}{{{float(last["val_loss"]):.2g}}}')

for tag, run in SEEDS.items():
  heads = rows(f'data/heads-{run}.csv')
  worst = max(heads, key=lambda h: float(h['loss_rise']))
  lines.append(f'\\def\\crit{tag}{{{worst["layer"]}.{worst["head"]}}}\\def\\critrise{tag}{{{float(worst["loss_rise"]):.2f}}}')

with open('build/values.tex', 'w') as f:
  f.write('\n'.join(lines) + '\n')
